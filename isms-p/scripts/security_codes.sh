declare -A ISMSP_CODES=(
    # 2.5 인증 및 권한관리
    ["IS-01"]="[2.5.1] 사용자 계정 관리"
    ["IS-02"]="[2.5.2] 사용자 식별"
    ["IS-03"]="[2.5.3] 사용자 인증"
    ["IS-04"]="[2.5.4] 비밀번호 관리"
    ["IS-05"]="[2.5.5] 특수 계정 및 권한 관리"
    ["IS-06"]="[2.5.6] 접근권한 검토"

    # 2.6 접근통제
    ["IS-07"]="[2.6.1] 네트워크 접근"
    ["IS-08"]="[2.6.2] 정보시스템 접근"
    ["IS-09"]="[2.6.6] 원격접근 통제"

    # 2.7 암호화 적용
    ["IS-10"]="[2.7.1] 암호정책 적용"
    ["IS-11"]="[2.7.2] 암호키 관리"

    # 2.9 시스템 및 서비스 운영관리
    ["IS-12"]="[2.9.3] 백업 및 복구관리"
    ["IS-13"]="[2.9.4] 로그 및 접속기록 관리"
    ["IS-14"]="[2.9.5] 로그 및 접속기록 점검"

    # 2.10 시스템 및 서비스 보안관리
    ["IS-15"]="[2.10.3] 공개서버 보안"
    ["IS-16"]="[2.10.8] 패치관리"
    ["IS-17"]="[2.10.9] 악성코드 통제"
)

# 점검 실행 순서 (연관 배열은 순서를 보장하지 않으므로 별도 정의)
ISMSP_ORDER=(
    IS-01 IS-02 IS-03 IS-04 IS-05 IS-06
    IS-07 IS-08 IS-09
    IS-10 IS-11
    IS-12 IS-13 IS-14
    IS-15 IS-16 IS-17
)

get_ismsp_category() {
    local code="$1"
    local num="${code#IS-}"
    num=$((10#$num))
    if   [ "$num" -ge 1  ] && [ "$num" -le 6  ]; then echo "인증 및 권한관리"
    elif [ "$num" -ge 7  ] && [ "$num" -le 9  ]; then echo "접근통제"
    elif [ "$num" -ge 10 ] && [ "$num" -le 11 ]; then echo "암호화 적용"
    elif [ "$num" -ge 12 ] && [ "$num" -le 14 ]; then echo "시스템 및 서비스 운영관리"
    else                                              echo "시스템 및 서비스 보안관리"
    fi
}
